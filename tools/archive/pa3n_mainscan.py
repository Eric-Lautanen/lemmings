import tools.datcommon as dc
import os

def find_all(pat, data, label):
    hits = []
    i = 0
    while True:
        i = data.find(pat, i)
        if i < 0: break
        hits.append(i)
        i += 1
    return hits

raw = open(os.path.join(dc.ORIG, 'main.dat'), 'rb').read()
print('raw size', len(raw))
pat = bytes([0x3f,0x3f,0x03,0x03,0x06,0x06,0x0c,0x0c,0x0c,0x0c,0x0c])
print('raw scan %:', find_all(pat, raw, ''))

secs = dc.decompress_dat(os.path.join(dc.ORIG, 'main.dat'))
print('sections:', len(secs))
for idx, s in enumerate(secs):
    print(f'sec{idx}: {len(s)} bytes')
    for name, p in [
        ('%', bytes([0x3f,0x3f,0x03,0x03,0x06,0x06,0x0c,0x0c,0x0c,0x0c,0x0c])),
        ('%lsb', bytes([0x3f,0x3f,0xc0,0xc0,0x60,0x60,0x30,0x30,0x30,0x30,0x30])),
        ('1', bytes([0x3f,0x3f,0x3f,0x0c,0x0c,0x0c,0x0c,0x0c,0x0c,0x0c,0x0c])),
        ('S', bytes([0x33,0x33,0x07,0x06,0x0e,0x0c,0x1c,0x18,0x38,0x33,0x33])),
        ('Slsb', bytes([0xcc,0xcc,0xe0,0x60,0x70,0x30,0x38,0x18,0x1c,0xcc,0xcc])),
        ('0', bytes([0x1e,0x3f,0x33,0x33,0x33,0x33,0x33,0x33,0x3f,0x3f,0x1e])),
    ]:
        h = find_all(p, s, '')
        if h:
            print(f'   {name}: {h}')